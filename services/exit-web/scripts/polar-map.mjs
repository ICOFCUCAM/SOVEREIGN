// Writes src/lib/polar-map.ts: the world's land in an azimuthal equidistant
// projection centred on the North Pole, for the map behind the hero's
// signature. Source: Natural Earth 1:110m land (public domain), as TopoJSON
// from the world-atlas package (ISC). Run once, with the data file's path:
//   npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
//   node scripts/polar-map.mjs package/land-110m.json
// No runtime dependency: the TopoJSON decode and the projection are below.
import fs from "node:fs";

const SIZE = 200, C = SIZE / 2, EDGE = -60; // view box; the map is cut at 60°S
const R = 96;                                 // radius of the 60°S edge
const K = R / (90 - EDGE);                    // units per degree of polar distance

/** Azimuthal equidistant about the North Pole; Greenwich points down, east runs anticlockwise. */
const project = ([lon, lat]) => {
  const rho = (90 - lat) * K, a = (lon * Math.PI) / 180;
  return [C + rho * Math.sin(a), C + rho * Math.cos(a)];
};

const topo = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
const arcs = topo.arcs.map((arc) => { let x = 0, y = 0; return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]); });
const ring = (ids) => ids.flatMap((i, k) => { const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i]; return k ? a.slice(1) : a; });
const polys = topo.objects.land.geometries.flatMap((g) => (g.type === "Polygon" ? [g.arcs] : g.arcs));
// keep every ring that reaches north of the edge (this drops Antarctica)
const rings = polys.flatMap((p) => p.map(ring)).filter((r) => Math.max(...r.map((p) => p[1])) > EDGE + 5);

// paths in tenths of a unit, relative moves (compact): the SVG scales them back by 0.1
const q = (p) => project(p).map((n) => Math.round(n * 10));
const path = (r, cut) => {
  let out = "", prev = null;
  r.forEach((p, i) => {
    const [x, y] = q(p);
    if (!prev || cut(i)) out += `M${x} ${y}`;
    else if (x !== prev[0] || y !== prev[1]) out += `l${x - prev[0]} ${y - prev[1]}`.replace(/ -/g, "-");
    prev = [x, y];
  });
  return out;
};
// the fill closes each ring; the outline breaks where a ring runs along the antimeridian (the data's cut
// through Chukotka), so no false coastline is drawn there
const seam = (a, b) => Math.abs(Math.abs(a[0]) - 180) < 1e-6 && Math.abs(Math.abs(b[0]) - 180) < 1e-6;
const fill = rings.map((r) => path(r, () => false) + "z").join("");
const coast = rings.map((r) => path(r, (i) => seam(r[i - 1], r[i]))).join("");

fs.writeFileSync(new URL("../src/lib/polar-map.ts", import.meta.url), `// GENERATED by scripts/polar-map.mjs — do not edit by hand.
// The world's land, azimuthal equidistant projection centred on the North
// Pole (Greenwich down), cut at 60°S. Natural Earth 1:110m land, public domain.
// The paths are in tenths of a view-box unit: draw them with transform="scale(.1)".
export const POLAR = { size: ${SIZE}, c: ${C}, r: ${R}, edge: ${EDGE}, k: ${K} } as const;
/** Radius in view-box units of a parallel. */
export const parallel = (lat: number): number => (90 - lat) * POLAR.k;
export const LAND_FILL = "${fill}";
export const LAND_COAST = "${coast}";
`);
console.log("polar map written:", rings.length, "rings,", fill.length + coast.length, "chars");
